<?php

declare(strict_types=1);

namespace Tests\Feature;

use App\Support\Db;
use App\Support\Firewall;
use InvalidArgumentException;
use Tests\TestCase;

final class FirewallTest extends TestCase
{
    private string $dir;

    private string $log;

    protected function setUp(): void
    {
        parent::setUp();
        $this->dir = (string) getenv('RADIUSONE_TEST_DIR');
        foreach (['/firewall/request', '/firewall/confirm', '/firewall-status/status.json', '/firewall-status/host.json', '/firewall-status/active.nft', '/nft.log', '/auto-confirm'] as $file) {
            @unlink($this->dir . $file);
        }
        @mkdir($this->dir . '/firewall');
        @mkdir($this->dir . '/firewall-status');
        // A stand-in for nft that records what it is asked to do, and fails when told to.
        $this->log = $this->dir . '/nft.log';
        $script = $this->dir . '/fake-nft';
        file_put_contents($script, "#!/bin/sh\n[ -f \"$this->dir/nft-fails\" ] && [ \"\$1\" = -c ] && { echo refused >&2; exit 1; }\necho \"ARGS \$*\" >> \"$this->log\"\ncase \"\$*\" in list*) exit 1;; esac\ncat >> \"$this->log\"\n[ \"\$1\" = -f ] && [ -f \"$this->dir/auto-confirm\" ] && cp \"$this->dir/auto-confirm\" \"$this->dir/firewall/confirm\"\nexit 0\n");
        chmod($script, 0755);
        @unlink($this->dir . '/nft-fails');
        Firewall::$nft = [$script];
        Firewall::$confirmSeconds = 1;
        $this->insertRow('nas', ['nasname' => '192.0.2.10', 'shortname' => 'r1', 'secret' => 'x']);
    }

    public function test_the_page_starts_off_with_the_template_and_the_visitor_as_management(): void
    {
        $this->actingAsOperator();
        $this->withServerVariables(['REMOTE_ADDR' => '198.51.100.7']);
        $this->get('/settings?tab=firewall')->assertOk();
        $this->assertFalse(Firewall::config()['enabled']);
        $this->assertSame(['198.51.100.7/32'], Firewall::config()['management_networks']);
        $rules = Firewall::rules();
        $this->assertSame(['80,443', '1812,1813'], array_column($rules, 'ports'));
        $this->assertSame(['', 'routers'], array_column($rules, 'source'));

        // Opening it again changes nothing, also after the rules were edited.
        Firewall::deleteRule($rules[0]['id']);
        $this->get('/settings?tab=firewall')->assertOk();
        $this->assertCount(1, Firewall::rules());
        Firewall::restoreTemplate('t');
        $this->assertCount(2, Firewall::rules());
    }

    public function test_rendering_keeps_management_first_and_uses_only_validated_values(): void
    {
        Firewall::ensureTemplate('203.0.113.5');
        Firewall::addRule(['action' => 'drop', 'protocol' => 'tcp', 'source' => '10.1.2.3/24', 'ports' => '3306', 'comment' => '"; flush ruleset; #'], 't', '203.0.113.5');
        $draft = Firewall::draft();
        $draft['config']['enabled'] = true;
        $script = Firewall::render($draft, [2222]);
        $this->assertStringContainsString('policy drop', $script);
        $this->assertStringContainsString('ip saddr @management4 tcp dport { 2222, 80, 443 } accept', $script);
        $this->assertStringContainsString('ip saddr @routers4 udp dport { 1812, 1813 } accept', $script);
        $this->assertStringContainsString('ip saddr 10.1.2.0/24 tcp dport 3306 drop', $script);
        $this->assertStringNotContainsString('flush', $script);
        $this->assertLessThan(strpos($script, 'tcp dport { 80, 443 } accept'), strpos($script, '@management4 tcp'));

        // A value tampered with in the database never reaches nft.
        $draft['config']['management_networks'] = ['1.1.1.1; flush ruleset'];
        $this->expectException(\RuntimeException::class);
        Firewall::render($draft);
    }

    public function test_off_or_empty_only_removes_the_table(): void
    {
        $this->assertSame(
            "# Generated by RadiusOne (Settings → Firewall). Do not edit: the next Apply replaces it.\ntable inet radiusone\ndelete table inet radiusone\n",
            Firewall::render(['config' => ['enabled' => false]])
        );
    }

    public function test_rules_that_would_cut_the_server_off_are_refused(): void
    {
        foreach ([
            ['action' => 'drop', 'protocol' => 'any'],
            ['action' => 'drop', 'protocol' => 'tcp', 'source' => '0.0.0.0/0'],
            ['action' => 'reject', 'protocol' => 'tcp', 'source' => '203.0.113.0/24'],
            ['action' => 'accept', 'protocol' => 'tcp', 'ports' => '70000'],
            ['action' => 'accept', 'protocol' => 'tcp', 'source' => 'nonsense'],
            ['action' => 'bad', 'protocol' => 'tcp'],
        ] as $values) {
            try {
                Firewall::cleanRule($values, '203.0.113.5');
                $this->fail('Accepted: ' . json_encode($values));
            } catch (InvalidArgumentException) {
                $this->addToAssertionCount(1);
            }
        }
    }

    public function test_turning_on_needs_the_visitor_in_the_management_networks(): void
    {
        Firewall::ensureTemplate('203.0.113.5');
        try {
            Firewall::enable('t', '198.51.100.9');
            $this->fail('Enabled from outside the management networks.');
        } catch (InvalidArgumentException $e) {
            $this->assertStringContainsString('198.51.100.9', $e->getMessage());
        }
        $this->assertFalse(Firewall::config()['enabled']);
        $this->assertFileDoesNotExist($this->dir . '/firewall/request');
    }

    public function test_confirmed_change_stays_and_is_saved_for_boot(): void
    {
        Firewall::ensureTemplate('203.0.113.5');
        $id = Firewall::enable('t', '203.0.113.5');
        $this->assertFileExists($this->dir . '/firewall/request');
        $this->assertTrue(Firewall::busy());

        // The stand-in for nft plays the portal: it confirms once the rules are loaded.
        file_put_contents($this->dir . '/auto-confirm', $id);
        $this->assertSame(0, Firewall::rootApply());
        $this->assertSame('applied', Firewall::status()['state']);
        $this->assertFalse(Firewall::busy());
        $this->assertStringContainsString('policy drop', (string) file_get_contents($this->dir . '/firewall-status/active.nft'));
        $this->assertStringContainsString('ARGS -c -f -', (string) file_get_contents($this->log));
    }

    public function test_no_confirmation_puts_the_previous_state_back(): void
    {
        Firewall::ensureTemplate('203.0.113.5');
        Firewall::enable('t', '203.0.113.5');
        $this->assertSame(1, Firewall::rootApply());
        $this->assertSame('rolled_back', Firewall::status()['state']);
        $this->assertFalse(Firewall::config()['enabled']);
        $this->assertNull(Firewall::active());
        $this->assertFileDoesNotExist($this->dir . '/firewall-status/active.nft');
        $this->assertStringContainsString('delete table inet radiusone', (string) file_get_contents($this->log));
    }

    public function test_only_who_applied_can_confirm(): void
    {
        file_put_contents($this->dir . '/firewall-status/status.json', json_encode(['state' => 'confirming', 'id' => 'abc', 'by' => 'alice', 'at' => time()]));
        $this->assertFalse(Firewall::confirm('abc', 'mallory'));
        $this->assertFalse(Firewall::confirm('other', 'alice'));
        $this->assertTrue(Firewall::confirm('abc', 'alice'));
    }

    public function test_rules_nft_refuses_change_nothing(): void
    {
        Firewall::ensureTemplate('203.0.113.5');
        touch($this->dir . '/nft-fails');
        Firewall::enable('t', '203.0.113.5');
        $this->assertSame(1, Firewall::rootApply());
        $this->assertSame('failed', Firewall::status()['state']);
        $this->assertStringContainsString('refused', (string) Firewall::status()['message']);
        $this->assertFalse(Firewall::config()['enabled']);
    }

    public function test_turning_off_needs_no_confirmation_and_keeps_the_rules(): void
    {
        Firewall::ensureTemplate('203.0.113.5');
        $id = Firewall::enable('t', '203.0.113.5');
        file_put_contents($this->dir . '/auto-confirm', $id);
        Firewall::rootApply();

        @unlink($this->dir . '/auto-confirm');
        Firewall::disable('t');
        $this->assertSame(0, Firewall::rootApply());
        $this->assertSame('disabled', Firewall::status()['state']);
        $this->assertFalse(Firewall::config()['enabled']);
        $this->assertCount(2, Firewall::rules());
        $this->assertStringNotContainsString('policy drop', (string) file_get_contents($this->dir . '/firewall-status/active.nft'));
    }

    public function test_sync_follows_routers_and_stays_quiet_otherwise(): void
    {
        Firewall::ensureTemplate('203.0.113.5');
        $this->assertSame('nothing to do', Firewall::sync());
        $id = Firewall::enable('t', '203.0.113.5');
        file_put_contents($this->dir . '/auto-confirm', $id);
        Firewall::rootApply();
        $this->assertSame('in force', Firewall::sync());
        $this->assertFileDoesNotExist($this->dir . '/firewall/request');

        $this->insertRow('nas', ['nasname' => '192.0.2.20', 'shortname' => 'r2', 'secret' => 'x']);
        $this->assertSame('loading the rules', Firewall::sync());
        $this->assertStringNotContainsString('"confirm":true', (string) file_get_contents($this->dir . '/firewall/request'));
        @unlink($this->dir . '/auto-confirm');
        $this->assertSame(0, Firewall::rootApply());
        $this->assertStringContainsString('192.0.2.20/32', (string) file_get_contents($this->dir . '/firewall-status/active.nft'));
        $this->assertSame('in force', Firewall::sync());
        // A router list change is not a pending change for the operator.
        $this->assertFalse(Firewall::pending());
    }

    public function test_a_shell_can_always_turn_it_off(): void
    {
        Firewall::ensureTemplate('203.0.113.5');
        $id = Firewall::enable('t', '203.0.113.5');
        file_put_contents($this->dir . '/auto-confirm', $id);
        Firewall::rootApply();
        $this->assertSame(0, Firewall::rootOff());
        $this->assertFalse(Firewall::config()['enabled']);
        $this->assertSame('disabled', Firewall::status()['state']);
        $this->assertSame('nothing to do', Firewall::sync());
    }

    public function test_only_settings_managers_reach_it(): void
    {
        $this->actingAsOperator('view');
        $this->get('/settings?tab=firewall')->assertForbidden();
        $this->post('/settings/firewall/enable')->assertForbidden();
        $this->assertSame(0, (int) Db::value('SELECT COUNT(*) FROM firewall_rules'));
    }

    public function test_buttons_work_end_to_end_in_the_portal(): void
    {
        $this->actingAsOperator();
        $this->withServerVariables(['REMOTE_ADDR' => '198.51.100.7']);
        $this->get('/settings?tab=firewall')->assertOk();
        $this->post('/settings/firewall/rules', ['action' => 'accept', 'protocol' => 'tcp', 'source' => '198.51.100.0/24', 'ports' => '8080', 'comment' => 'test', 'minutes' => '60'])->assertRedirect('/settings?tab=firewall');
        $this->assertCount(3, Firewall::rules());
        $this->assertNotNull(Firewall::rules()[2]['expires_at']);
        $this->post('/settings/firewall/management', ['networks' => "198.51.100.0/24\n2001:db8::/32 # office"])->assertRedirect();
        $this->assertSame(['198.51.100.0/24', '2001:db8::/32'], Firewall::config()['management_networks']);
        $this->post('/settings/firewall/enable')->assertRedirect();
        $this->assertTrue(Firewall::config()['enabled']);
        $this->assertFileExists($this->dir . '/firewall/request');
    }
}
